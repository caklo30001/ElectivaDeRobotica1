if v1.size == v2.size:
    producto_punto = np.dot(v1, v2)
    print(f"Producto Punto (Escalar): {producto_punto}")
else:
    print(f"Error: El Producto Punto requiere que ambos tengan {v1.size} elementos (v2 tiene {v2.size}).")

# 3. PRODUCTO CRUZ (Validación R3)
