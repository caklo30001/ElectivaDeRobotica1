import math

def calcular_resistencia_pt100(t):
    # coeficientes de Callendar-Van Dusen
    R0 = 100.0
    A = 3.9083e-3
    B = -5.775e-7
    C = -4.183e-12

    if t >= 0:
        rt = R0 * (1 + A * t + B * t**2)
    else:
        rt = R0 * (1 + A * t + B * t**2 + C * (t - 100) * t**3)
    return rt

