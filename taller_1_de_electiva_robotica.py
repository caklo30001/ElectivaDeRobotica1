#5. Realice en funciones las rotaciones en X, Y y Z, donde se tenga un parámetro de entrada (ángulo)
#y un parámetro de salida (matriz).

import math

def rotacion_x(angulo_grados):
    # Convertimos a radianes porque math.sin/cos
    rad = math.radians(angulo_grados)
    c, s = math.cos(rad), math.sin(rad)

    # Construimos la matriz como una lista de listas
    matriz = [
        [1, 0,  0],
        [0, c, -s],
        [0, s,  c]
    ]
    return matriz

def rotacion_y(angulo_grados):
    rad = math.radians(angulo_grados)
    c, s = math.cos(rad), math.sin(rad)

    matriz = [
        [ c, 0, s],
        [ 0, 1, 0],
        [-s, 0, c]
    ]
    return matriz

def rotacion_z(angulo_grados):
    rad = math.radians(angulo_grados)
    c, s = math.cos(rad), math.sin(rad)

    matriz = [
        [c, -s, 0],
        [s,  c, 0],
        [0,  0, 1]
    ]
    return matriz

# --- Ejemplo de uso para probar el programa ---
angulo = 45
m_z = rotacion_z(angulo)

print(f"Matriz de Rotación en Z para {angulo}°:")
print("-" * 40)
for fila in m_z:
    print(fila)
